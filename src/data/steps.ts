const conceptFallback = (topic: Topic): string[] => [
  `Identify the invariant or rule that defines ${topic.title}.`,
  `Set up the ${topic.section.toLowerCase()} state needed to apply that rule.`,
  `Perform the specific ${topic.title.toLowerCase()} operation and observe how the state changes.`,
  `Check the result against the defining invariant before continuing or returning the answer.`,
  `Repeat only for the remaining part of the problem, then state the final result and complexity.`,
];

export function getLearningSteps(topic: Topic): string[] {
  if (topic.id.startsWith('tc-')) {
    return complexitySteps[topic.title] ?? conceptFallback(topic);
  }

  if (stepsById[topic.id]) return stepsById[topic.id];
  if (generatedTreeSteps[topic.title]) return generatedTreeSteps[topic.title];

  // Prefix-aware handling keeps repeated operation names from sharing one generic story.
  if (topic.id.startsWith('tree-bst-')) {
    return operationSteps[topic.title] ?? conceptFallback(topic);
  }

  if (topic.category === 'Stack' && operationSteps[topic.title]) {
    return operationSteps[topic.title];
  }

  if (topic.category === 'Queue' && topic.title === 'Is Empty') return stepsById['queue-empty'];
  if (topic.category === 'Queue' && topic.title === 'Is Full') return stepsById['queue-full'];
  if (topic.category === 'Queue' && topic.title === 'Peek Front') return stepsById['queue-peek'];

  if (topic.category === 'Linked List' && operationSteps[topic.title]) {
    return operationSteps[topic.title];
  }

  return conceptFallback(topic);
}
